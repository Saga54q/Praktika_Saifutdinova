    fldChar1.set(qn('w:fldCharType'), 'begin')
    instrText = OxmlElement('w:instrText')
    instrText.set(qn('xml:space'), 'preserve')
    instrText.text = 'TOC \\o "1-2" \\h \\z \\u'
    fldChar2 = OxmlElement('w:fldChar')
    fldChar2.set(qn('w:fldCharType'), 'separate')
    fldChar3 = OxmlElement('w:fldChar')
    fldChar3.set(qn('w:fldCharType'), 'end')
    run._r.append(fldChar1)
    run._r.append(instrText)
    run._r.append(fldChar2)
    r2 = p.add_run("Обновите содержание в Microsoft Word: щёлкните правой кнопкой по полю и выберите «Обновить поле».")
    set_run_font(r2, size=11, italic=True)
    p.runs[-1]._r.addnext(fldChar3) if False else None
    # append end char properly
    run3 = p.add_run()
    run3._r.append(fldChar3)
    set_run_font(run3, size=12)
    doc.add_page_break()



def set_run_font(run, size=14, bold=False, italic=False, name="Times New Roman"):
    run.font.name = name
    run._element.rPr.rFonts.set(qn('w:eastAsia'), name)
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic


def style_paragraph(p, alignment=WD_ALIGN_PARAGRAPH.JUSTIFY, indent=Cm(1.25), before=0, after=0, line=1.5):
    pf = p.paragraph_format
    pf.alignment = alignment
    pf.first_line_indent = indent
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.line_spacing = line


def add_para(doc, text="", size=14, bold=False, italic=False, alignment=WD_ALIGN_PARAGRAPH.JUSTIFY, indent=Cm(1.25), before=0, after=0, line=1.5, keep_with_next=False, page_break_before=False):
    p = doc.add_paragraph()
    style_paragraph(p, alignment=alignment, indent=indent, before=before, after=after, line=line)
    if keep_with_next:
        p.paragraph_format.keep_with_next = True
    if page_break_before:
        p.paragraph_format.page_break_before = True
    if text:
        run = p.add_run(text)
        set_run_font(run, size=size, bold=bold, italic=italic)
    return p


def add_empty(doc, n=1):
    for _ in range(n):
        add_para(doc, "", indent=None, alignment=WD_ALIGN_PARAGRAPH.LEFT)


def add_center(doc, text, size=14, bold=False, italic=False, before=0, after=0):
    return add_para(doc, text, size=size, bold=bold, italic=italic, alignment=WD_ALIGN_PARAGRAPH.CENTER, indent=None, before=before, after=after)


def add_right(doc, text, size=14, bold=False, italic=False, before=0, after=0):
    return add_para(doc, text, size=size, bold=bold, italic=italic, alignment=WD_ALIGN_PARAGRAPH.RIGHT, indent=None, before=before, after=after)


def add_left(doc, text, size=14, bold=False, italic=False, before=0, after=0, indent=None):
    return add_para(doc, text, size=size, bold=bold, italic=italic, alignment=WD_ALIGN_PARAGRAPH.LEFT, indent=indent, before=before, after=after)


def add_heading(doc, text, level=1):
    # level 1: chapter, level 2: section
    p = doc.add_paragraph()
    if level == 1:
        p.paragraph_format.page_break_before = True
        style_paragraph(p, alignment=WD_ALIGN_PARAGRAPH.CENTER, indent=None, before=0, after=12, line=1.5)
        run = p.add_run(text.upper() if not text.isupper() else text)
        set_run_font(run, size=14, bold=True)
    else:
        style_paragraph(p, alignment=WD_ALIGN_PARAGRAPH.JUSTIFY, indent=Cm(1.25), before=6, after=6, line=1.5)
        run = p.add_run(text)
        set_run_font(run, size=14, bold=True)
    p.paragraph_format.keep_with_next = True
    return p


def set_cell_text(cell, text, size=12, bold=False, italic=False, alignment=WD_ALIGN_PARAGRAPH.LEFT):
    cell.text = ""
    p = cell.paragraphs[0]
    style_paragraph(p, alignment=alignment, indent=None, before=0, after=0, line=1.0)
    run = p.add_run(text)
    set_run_font(run, size=size, bold=bold, italic=italic)


def add_table(doc, headers, rows, col_widths=None):
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = 'Table Grid'
    table.autofit = True
    hdr = table.rows[0].cells
    for i, h in enumerate(headers):
        set_cell_text(hdr[i], h, size=11, bold=True, alignment=WD_ALIGN_PARAGRAPH.CENTER)
    for row in rows:
        cells = table.add_row().cells
        for i, val in enumerate(row):
            set_cell_text(cells[i], str(val), size=11, alignment=WD_ALIGN_PARAGRAPH.LEFT)
    doc.add_paragraph()  # spacer
    return table


def add_page_number(section):
    footer = section.footer
    p = footer.paragraphs[0] if footer.paragraphs else footer.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = None
    # clear existing
    p.clear()
    run = p.add_run()
    set_run_font(run, size=12)
    fldChar1 = OxmlElement('w:fldChar')
    fldChar1.set(qn('w:fldCharType'), 'begin')
    instrText = OxmlElement('w:instrText')
    instrText.text = 'PAGE'
    fldChar2 = OxmlElement('w:fldChar')
    fldChar2.set(qn('w:fldCharType'), 'end')
    run._r.extend([fldChar1, instrText, fldChar2])



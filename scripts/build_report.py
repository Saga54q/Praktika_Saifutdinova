def make_placeholder(path: Path, title: str, subtitle: str = "Место для фактического скриншота приложения"):
    from PIL import Image, ImageDraw, ImageFont
    path.parent.mkdir(parents=True, exist_ok=True)
    img = Image.new('RGB', (1280, 720), color=(245, 245, 245))
    draw = ImageDraw.Draw(img)
    draw.rectangle([20, 20, 1259, 699], outline=(80, 80, 80), width=3)
    draw.rectangle([40, 40, 1239, 679], outline=(160, 160, 160), width=1)
    try:
        font_big = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 32)
        font_small = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 22)
    except Exception:
        font_big = ImageFont.load_default()
        font_small = ImageFont.load_default()
    # wrap title
    lines = []
    for part in title.split('\n'):
        lines.append(part)
    y = 280
    for line in lines:
        bbox = draw.textbbox((0,0), line, font=font_big)
        w = bbox[2]-bbox[0]
        draw.text(((1280-w)/2, y), line, fill=(40,40,40), font=font_big)
        y += 45
    bbox = draw.textbbox((0,0), subtitle, font=font_small)
    w = bbox[2]-bbox[0]
    draw.text(((1280-w)/2, y+20), subtitle, fill=(100,100,100), font=font_small)
    img.save(path)


def add_picture_with_caption(doc, image_path: Path, caption: str, width_mm=160):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = None
    run = p.add_run()
    try:
        run.add_picture(str(image_path), width=Mm(width_mm))
    except Exception as e:
        run.add_text(f"[Не удалось вставить изображение: {image_path.name}: {e}]")
        set_run_font(run, size=11, italic=True)
    cap = doc.add_paragraph()
    style_paragraph(cap, alignment=WD_ALIGN_PARAGRAPH.CENTER, indent=None, before=2, after=10, line=1.0)
    r = cap.add_run(caption)
    set_run_font(r, size=12, italic=False)


